    private void listarPrestamos() {
        DefaultTableModel modelo = new DefaultTableModel();
        modelo.addColumn("ID");
        modelo.addColumn("Libro");
        modelo.addColumn("Usuario");
        modelo.addColumn("Fecha Salida");
        modelo.addColumn("Estado");

        Prestamo[] datos = PrestamoDAO.obtener();
        int cantidad = PrestamoDAO.getCantidad();

        for (int i = 0; i < cantidad; i++) {
            Prestamo p = datos[i];
            if (p != null) {
                modelo.addRow(new Object[]{
                    p.getId(),
                    p.getLibro().getTitulo(),
                    p.getUsuario().getNombres(),
                    p.getFechaSalida(),
                    p.isEstado() ? "Activo" : "Finalizado"
                });
            }
        }
        tablaPrestamos.setModel(modelo);
    }

    private void filtrarPrestamos() {
        String filtro = txtCodUsr.getText().toLowerCase().trim();
        DefaultTableModel modelo = new DefaultTableModel();
        modelo.addColumn("ID");
        modelo.addColumn("Libro");
        modelo.addColumn("Usuario");
        modelo.addColumn("Fecha Salida");
        modelo.addColumn("Estado");

        Prestamo[] datos = PrestamoDAO.obtener();
        int cantidad = PrestamoDAO.getCantidad();

        for (int i = 0; i < cantidad; i++) {
            Prestamo p = datos[i];
            if (p != null) {
                String id = p.getId().toLowerCase();
                String libro = p.getLibro().getTitulo().toLowerCase();
                String usuario = p.getUsuario().getNombres().toLowerCase();

                if (filtro.isEmpty() || id.contains(filtro) || libro.contains(filtro) || usuario.contains(filtro)) {
                    modelo.addRow(new Object[]{
                        p.getId(),
                        p.getLibro().getTitulo(),
                        p.getUsuario().getNombres(),
                        p.getFechaSalida(),
                        p.isEstado() ? "Activo" : "Finalizado"
                    });
                }
            }
        }
        tablaPrestamos.setModel(modelo);
    }

